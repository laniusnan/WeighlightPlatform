import { createFileRoute } from "@tanstack/react-router"
import { Check, Copy, FileArchive, PackageCheck, RefreshCw, Rocket } from "lucide-react"
import { useEffect, useState } from "react"

import { methodLabel } from "@/components/lab/constants"
import { useI18n } from "@/components/lab/i18n"
import { Button, Card, EmptyState, SelectField } from "@/components/lab/ui"
import { apiListTasks, taskDeployPath, taskDownloadPath } from "@/services/api"
import { downloadBlob } from "@/services/http"
import { formatBytes } from "@/services/format"
import type { TaskPublic } from "@/services/types"

export const Route = createFileRoute("/lab/export")({
  component: ExportPage,
  head: () => ({ meta: [{ title: "Deploy - AI Model Lightweight Platform" }] }),
})

const DOCKERFILE_SAMPLE = `FROM python:3.11-slim
WORKDIR /app
COPY model ./model
RUN pip install --no-cache-dir fastapi uvicorn numpy onnxruntime
COPY serve.py ./serve.py
EXPOSE 8000
CMD ["python", "serve.py"]`

const SERVE_SAMPLE = `# FastAPI inference server (generated by deploy-export)
import os
import numpy as np
from fastapi import FastAPI

app = FastAPI(title="Model Server")

# onnxruntime CPU / OpenVINO auto-selected
# POST /predict  ->  {"inputs": [...], "input_shape": [...]}
# Test: docker run -p 8000:8000 model-server`

function CopyText({ text }: { text: string }) {
  const { t } = useI18n()
  const [copied, setCopied] = useState(false)
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text)
    } catch {
      /* ignore */
    }
    setCopied(true)
    window.setTimeout(() => setCopied(false), 1500)
  }
  return (
    <Button size="sm" variant="outline" onClick={() => void copy()}>
      {copied ? <Check size={13} className="text-[var(--lb-success)]" /> : <Copy size={13} />}
      {copied ? t("已复制", "Copied") : t("复制", "Copy")}
    </Button>
  )
}

function ExportPage() {
  const { t } = useI18n()
  const [tasks, setTasks] = useState<TaskPublic[]>([])
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState("")
  const [taskId, setTaskId] = useState("")

  const load = async () => {
    setLoading(true)
    setError("")
    try {
      const page = await apiListTasks({ limit: 200 })
      setTasks(page.data.filter((task) => task.status === "succeeded"))
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e))
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    void load()
  }, [])

  const task = tasks.find((item) => item.id === taskId) ?? tasks[0] ?? null
  const modelName = task?.model_name ?? (task ? task.id.slice(0, 8) : "model")
  const ratio =
    task && typeof task.metrics?.ratio === "number" ? `${task.metrics.ratio.toFixed(2)}x` : null

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-end justify-between gap-4">
        <div>
          <p className="lb-section">{t("部署导出", "Deploy & Export")}</p>
          <h1 className="mt-1 text-2xl font-bold tracking-tight text-[var(--lb-text)]">
            {t("部署导出", "Deploy & Export")}
          </h1>
          <p className="lb-muted mt-1 text-sm">
            {t(
              "选择已完成的压缩任务，导出含 Dockerfile / serve.py / model_card 的自包含部署包",
              "Pick a finished task and export a self-contained package (Dockerfile / serve.py / model_card).",
            )}
          </p>
        </div>
        <Button variant="outline" onClick={() => void load()} disabled={loading}>
          <RefreshCw size={14} className={loading ? "animate-spin" : ""} /> {t("刷新列表", "Refresh")}
        </Button>
      </div>

      {error && (
        <div className="rounded-md border border-[var(--lb-danger)]/30 bg-[var(--lb-danger-soft)] px-4 py-2.5 text-sm text-[var(--lb-danger)]">
          {error}
        </div>
      )}

      {!loading && tasks.length === 0 && (
        <Card className="p-6">
          <EmptyState
            title={t("暂无可导出的任务", "No exportable tasks yet")}
            description={t(
              "需要至少一个「已完成」的压缩任务，其产物才能打包为部署镜像。",
              "At least one finished compression task is required to build a deployable image.",
            )}
          />
        </Card>
      )}

      {tasks.length > 0 && (
        <>
          <Card className="p-6">
            <div className="flex flex-wrap items-end justify-between gap-4">
              <SelectField
                label={t("选择已完成任务", "Select a finished task")}
                className="min-w-72 flex-1"
                value={task?.id ?? ""}
                onChange={(e) => setTaskId(e.target.value)}
              >
                {tasks.map((item) => (
                  <option key={item.id} value={item.id}>
                    {item.model_name ?? item.id.slice(0, 8)} · {methodLabel(item.method)}（
                    {formatBytes(item.output_size_bytes ?? 0)}）
                  </option>
                ))}
              </SelectField>
              <div className="flex items-center gap-2">
                {task && (
                  <>
                    <Button
                      variant="outline"
                      onClick={() =>
                        void downloadBlob(taskDownloadPath(task.id), `${task.method}_result`)
                      }
                    >
                      <PackageCheck size={14} /> {t("下载压缩产物", "Download artifact")}
                    </Button>
                    <Button
                      onClick={() =>
                        void downloadBlob(taskDeployPath(task.id), `deploy_${modelName}.zip`)
                      }
                    >
                      <FileArchive size={14} /> {t("一键导出部署包", "Export package")}
                    </Button>
                  </>
                )}
              </div>
            </div>
            {task && (
              <div className="mt-5 grid gap-3 text-sm sm:grid-cols-4">
                {[
                  { label: t("模型", "Model"), value: modelName },
                  { label: t("压缩方法", "Method"), value: methodLabel(task.method) },
                  { label: t("体积比", "Size ratio"), value: ratio ?? "—" },
                  { label: t("产物大小", "Output size"), value: formatBytes(task.output_size_bytes ?? 0) },
                ].map((cell) => (
                  <div key={cell.label} className="rounded-lg border border-[var(--lb-border)] bg-[var(--lb-surface-2)] p-3">
                    <p className="lb-muted text-xs">{cell.label}</p>
                    <p className="mt-1 truncate font-semibold">{cell.value}</p>
                  </div>
                ))}
              </div>
            )}
          </Card>

          <Card className="p-6">
            <div className="mb-3 flex items-center gap-2">
              <Rocket size={16} className="text-[var(--lb-primary)]" />
              <h2 className="text-[15px] font-semibold text-[var(--lb-text)]">
                {t("离线部署三步", "Offline deploy in 3 steps")}
              </h2>
            </div>
            <ol className="space-y-3 text-sm leading-relaxed">
              {[
                {
                  title: t("导出部署包", "Export the package"),
                  body: t(
                    "点击上方「一键导出部署包」，得到含 model/、Dockerfile、serve.py、model_card.json 的 zip（由后端真实生成）。",
                    "Click Export package to download a zip containing model/, Dockerfile, serve.py and model_card.json.",
                  ),
                },
                {
                  title: t("构建镜像（需 Docker）", "Build the image (Docker)"),
                  body: t("解压后执行 ", "Unzip then run "),
                },
                {
                  title: t("启动并推理", "Run & infer"),
                  body: t("构建后启动并调用 /predict。", "Start the container and call POST /predict."),
                },
              ].map((step, i) => (
                <li key={step.title} className="flex gap-3">
                  <span className="flex size-6 shrink-0 items-center justify-center rounded-full bg-[var(--lb-primary-soft)] font-mono text-xs font-bold text-[var(--lb-primary)]">
                    {i + 1}
                  </span>
                  <div>
                    <p className="font-semibold">{step.title}</p>
                    <p className="lb-muted text-[13px]">{step.body}</p>
                  </div>
                </li>
              ))}
            </ol>
          </Card>

          <div className="grid gap-6 lg:grid-cols-2">
            <Card className="p-6">
              <div className="mb-3 flex items-center justify-between">
                <h3 className="text-sm font-semibold text-[var(--lb-text)]">Dockerfile</h3>
                <CopyText text={DOCKERFILE_SAMPLE} />
              </div>
              <pre className="lb-code">{DOCKERFILE_SAMPLE}</pre>
            </Card>
            <Card className="p-6">
              <div className="mb-3 flex items-center justify-between">
                <h3 className="text-sm font-semibold text-[var(--lb-text)]">serve.py</h3>
                <CopyText text={SERVE_SAMPLE} />
              </div>
              <pre className="lb-code">{SERVE_SAMPLE}</pre>
              <p className="lb-muted mt-3 text-xs">
                {t(
                  "实际 serve.py 由 deploy-export 按产物类型自动生成（onnxruntime / OpenVINO），以导出的 zip 内文件为准。",
                  "The actual serve.py is generated per artifact (onnxruntime / OpenVINO) inside the downloaded zip.",
                )}
              </p>
            </Card>
          </div>
        </>
      )}
    </div>
  )
}
